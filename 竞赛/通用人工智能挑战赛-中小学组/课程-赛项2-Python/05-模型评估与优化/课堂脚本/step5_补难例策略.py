"""
【任务卡】第5讲 步骤5（收官）：补难例策略生成器
任务：把"误判类型 -> 该补什么图"写成规则，生成你的补图清单。
猜一猜：假阳 4 假阴 1 时，按策略该补几类图？各补什么？
试一试：改两个数字再跑——清单怎么跟着变？这就是"评估驱动补数据"。
"""
def plan(fp, fn):
    """按误判类型生成补难例清单"""
    todo = []
    if fp > 2:
        todo.append("假阳偏多 -> 补 3~5 类相似非橙子：橘子、橙色球、橙色西红柿、橙色包装盒")
    elif fp:
        todo.append("假阳不多 -> 少量补最易混的橘子/橙色球")
    if fn > 2:
        todo.append("假阴偏多 -> 补多变化橙子：暗处/逆光、远小/近大、背景杂乱、被遮挡")
    elif fn:
        todo.append("假阴不多 -> 少量补不同光线角度的橙子")
    todo.append("两类保持数量接近，重查健康度")
    return todo

print("场景一：假阳 4，假阴 1")
for item in plan(4, 1):
    print("  -", item)

print("\n场景二：假阳 1，假阴 3")
for item in plan(1, 3):
    print("  -", item)

print("\n补一张'难图'胜过十张'类似图'——难例优先于简单重复")
